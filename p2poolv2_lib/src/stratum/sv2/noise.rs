//! Noise NX transport for Stratum V2, signed by the operator's authority key.
//!
//! The responder handshake answers the initiator's ElligatorSwift key with
//! its own ephemeral key, its static key, and a certificate the authority
//! key signs; the miner checks that signature against the authority public
//! key it was given. After the handshake every frame is encrypted: the
//! header as one AEAD message and the payload in chunks.
//!
//! The authority key is the operator's, configured from an external tool.
//! The ephemeral and static keys of each session are generated by
//! `noise_sv2` for that handshake alone, as the Noise protocol requires.

use crate::config::Sv2Authority;
use codec_sv2::{
    Decrypted, Handshake, NoiseDecoder, NoiseEncoder, TransportDecryptState, TransportEncryptState,
};
use framing_sv2::framing::SerializedFrame;
use noise_sv2::{ELLSWIFT_ENCODING_SIZE, Responder};
use std::time::Duration;
use tokio::io::{AsyncReadExt, AsyncWriteExt};
use tokio::time::timeout;

/// How long a client has to send its handshake key after connecting.
const HANDSHAKE_TIMEOUT: Duration = Duration::from_secs(10);

/// One connection's encryption and decryption state after the handshake.
pub(crate) struct NoiseTransport {
    decoder: NoiseDecoder,
    encoder: NoiseEncoder,
    encrypt: TransportEncryptState,
    /// Taken while a frame is decrypted, then put back.
    decrypt: Option<TransportDecryptState>,
    inbox: Vec<u8>,
}

impl NoiseTransport {
    /// Run the responder side of the handshake on `stream`.
    pub(crate) async fn accept<Stream>(
        stream: &mut Stream,
        authority: &Sv2Authority,
    ) -> Result<Self, String>
    where
        Stream: AsyncReadExt + AsyncWriteExt + Unpin,
    {
        let responder = Responder::from_authority_kp(
            &authority.public_key,
            &authority.secret_key,
            Duration::from_secs(authority.cert_validity_secs),
        )
        .map_err(|error| format!("invalid authority key pair: {error:?}"))?;
        let mut initiator_key = [0u8; ELLSWIFT_ENCODING_SIZE];
        timeout(HANDSHAKE_TIMEOUT, stream.read_exact(&mut initiator_key))
            .await
            .map_err(|_| "handshake timed out".to_string())?
            .map_err(|error| error.to_string())?;
        let (message, transport) = Handshake::responder(responder)
            .step_1(initiator_key)
            .map_err(|error| format!("handshake failed: {error:?}"))?;
        let mut encoder = NoiseEncoder::new();
        let reply = encoder.encode_handshake(message);
        stream
            .write_all(reply.as_ref())
            .await
            .map_err(|error| error.to_string())?;
        let (encrypt, decrypt) = transport.split();
        Ok(Self {
            decoder: NoiseDecoder::new(),
            encoder,
            encrypt,
            decrypt: Some(decrypt),
            inbox: Vec::with_capacity(4096),
        })
    }

    /// Decrypt `incoming` into complete messages: type and payload.
    pub(crate) fn decode(&mut self, incoming: &[u8]) -> Result<Vec<(u8, Vec<u8>)>, String> {
        self.inbox.extend_from_slice(incoming);
        let mut messages = Vec::new();
        let mut reading = true;
        while reading {
            let room = self.decoder.writable_len();
            if room == 0 || self.inbox.len() < room {
                reading = false;
            } else {
                self.decoder.writable().copy_from_slice(&self.inbox[..room]);
                self.inbox.drain(..room);
                let state = self
                    .decrypt
                    .take()
                    .ok_or("decryption state lost after an earlier error")?;
                match self
                    .decoder
                    .next_transport_frame(state)
                    .map_err(|error| format!("{error:?}"))?
                {
                    Decrypted::Frame(mut frame, state) => {
                        self.decrypt = Some(state);
                        let message_type = frame.header().msg_type();
                        messages.push((message_type, frame.payload().to_vec()));
                    }
                    Decrypted::Incomplete(_, state) => self.decrypt = Some(state),
                }
            }
        }
        Ok(messages)
    }

    /// Encrypt one plaintext frame for the wire.
    pub(crate) fn encrypt(&mut self, frame: Vec<u8>) -> Result<Vec<u8>, String> {
        let serialized = SerializedFrame::<Vec<u8>>::from_bytes(frame)
            .map_err(|_| "outgoing frame is incomplete".to_string())?;
        self.encoder
            .encode_transport(serialized, &mut self.encrypt)
            .map_err(|error| format!("{error:?}"))
    }
}
